#!/usr/bin/env bash
# install-guard-test.sh - civicrm_installed() must agree with what a real
# `cv core:install` actually produces.
#
# The failures this guards
# ------------------------
# Version 1 grepped the settings file for $civicrm_setting['dsn']. The DSN is a
# CONSTANT, not a setting, so it never matched.
#
# Version 2 counted top-level $civicrm_setting keys and required 3. A real
# install has exactly ONE - 'domain' - so version 2 answered "not installed" for
# every CORRECT install. The installer then re-ran forever, and its disagreement
# with cv's own "civicrm.settings.php already exists" prompt is what produced the
# interactive Abort.
#
# The fixture below is copied in shape from a real file generated by
# `cv core:install` against MariaDB on the 6.18.2 standalone release: one
# top-level key, six domain entries, the DSN and base URL as defines. The test
# asserts that shape first, so a future edit cannot quietly stop exercising the
# real case.
set -uo pipefail

BOX="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
FAIL=0
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

pass() { printf '  [ ok ] %s\n' "$*"; }
fail() { printf '  [FAIL] %s\n' "$*"; FAIL=1; }

# shellcheck source=../scripts/lib.sh
. "$BOX/scripts/lib.sh"

# A fake app root. detect_app_root() insists on civicrm.standalone.php, which is
# also what makes it refuse to guess: the marker is present here deliberately.
make_app() {
  local d="$TMP/$1"
  mkdir -p "$d/private"
  printf '<?php\n' > "$d/civicrm.standalone.php"
  printf '%s' "$2" > "$d/private/civicrm.settings.php"
  printf '%s' "$d"
}

app_without_settings() {
  local d="$TMP/$1"
  mkdir -p "$d/private"
  printf '<?php\n' > "$d/civicrm.standalone.php"
  printf '%s' "$d"
}

installed() {
  local d="$1" rc
  CIVICRM_APP_DIR="$d"
  civicrm_installed
  rc=$?
  # shellcheck disable=SC2034  # read by detect_app_root() inside the sourced lib.sh
  CIVICRM_APP_DIR=""
  return "$rc"
}

# --- The fixture must look like the real thing -------------------------------
REAL="$(make_app real '<?php
define('"'"'CIVICRM_UF'"'"', '"'"'Standalone'"'"');
define('"'"'CIVICRM_DSN'"'"', '"'"'mysql://civicrm:pw@10.0.0.1:3306/civicrm?new_link=true'"'"');
define('"'"'CIVICRM_UF_BASEURL'"'"', '"'"'https://dev.civi.sioldata.com'"'"');
define('"'"'CIVICRM_SITE_KEY'"'"', '"'"'y7XSmXof0loQ9yhr4qpIp50E1mUEehBa1VlW03QV'"'"');
$civicrm_setting['"'"'domain'"'"']['"'"'uploadDir'"'"'] = '"'"'/var/lib/civicrm-data/private/upload'"'"';
$civicrm_setting['"'"'domain'"'"']['"'"'imageUploadDir'"'"'] = '"'"'/var/lib/civicrm-data/private/persist'"'"';
$civicrm_setting['"'"'domain'"'"']['"'"'customFileUploadDir'"'"'] = '"'"'/var/lib/civicrm-data/private/custom'"'"';
$civicrm_setting['"'"'domain'"'"']['"'"'extensionsDir'"'"'] = '"'"'/var/lib/civicrm-data/ext'"'"';
$civicrm_setting['"'"'domain'"'"']['"'"'templateCompileDir'"'"'] = '"'"'/var/lib/civicrm-data/private/cache'"'"';
$civicrm_setting['"'"'domain'"'"']['"'"'userFrameworkResourceURL'"'"'] = '"'"'https://dev.civi.sioldata.com/civicrm'"'"';
')"

TOPS="$(php -r 'require $argv[1]; echo count($civicrm_setting);' "$REAL/private/civicrm.settings.php" 2>/dev/null)"
DOMAIN="$(php -r 'require $argv[1]; echo count($civicrm_setting["domain"]);' "$REAL/private/civicrm.settings.php" 2>/dev/null)"

echo "=== the fixture has the shape of a real install ==="
[ "$TOPS" = "1" ] \
  && pass "exactly 1 top-level \$civicrm_setting key (a real install has 'domain' only)" \
  || fail "fixture has ${TOPS:-?} top-level keys; a real install has 1, so this no longer tests reality"
[ "$DOMAIN" = "6" ] \
  && pass "domain holds 6 entries, as cv writes" \
  || fail "fixture domain has ${DOMAIN:-?} entries, expected 6"

echo
echo "=== a real, correctly installed settings file ==="
if installed "$REAL"; then
  pass "civicrm_installed returns 0 (would NOT re-run the installer)"
else
  fail "civicrm_installed returns 1 for a valid install - this is the bug that looped forever"
fi

echo
echo "=== files that are NOT an install ==="
PLACEHOLDER="$(make_app placeholder '<?php
define('"'"'CIVICRM_DSN'"'"', '"'"'mysql://%%dbUser%%:%%dbPass%%@%%dbHost%%/%%dbName%%?new_link=true'"'"');
')"
if installed "$PLACEHOLDER"; then
  fail "an unrendered template DSN (%%) was accepted as installed"
else
  pass "the unrendered template placeholder is rejected"
fi

EMPTY="$(make_app empty '<?php
')"
if installed "$EMPTY"; then
  fail "an empty settings file was accepted as installed"
else
  pass "an empty settings file is rejected"
fi

MISSING="$(app_without_settings missing)"
if installed "$MISSING"; then
  fail "a missing settings file was accepted as installed"
else
  pass "a missing settings file is rejected"
fi

# The anti-regression for version 2: plenty of settings, no DSN. If someone
# reintroduces a count-based threshold this passes and the test fails.
MANY="$(make_app many '<?php
$civicrm_setting['"'"'domain'"'"']['"'"'uploadDir'"'"'] = '"'"'/tmp/a'"'"';
$civicrm_setting['"'"'debug'"'"']['"'"'enabled'"'"'] = 1;
$civicrm_setting['"'"'mailing'"'"']['"'"'batch'"'"'] = 10;
')"
if installed "$MANY"; then
  fail "a file with 3 settings but no CIVICRM_DSN was accepted - counting keys is not evidence"
else
  pass "three settings but no DSN is rejected (a key count is not evidence)"
fi

echo
[ "$FAIL" -eq 0 ] && echo "  install-guard test PASSED" || echo "  install-guard test FAILED"
exit "$FAIL"
